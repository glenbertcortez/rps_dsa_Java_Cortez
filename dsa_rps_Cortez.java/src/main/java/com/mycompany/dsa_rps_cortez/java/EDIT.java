    // UPDATE — I-save ang pagbabago
    private void performUpdate() {
        String name = jTextField5.getText().trim();
        String year = jTextField3.getText().trim();
        String section = jTextField4.getText().trim();
        
        // Validation
        if (name.isEmpty() || year.isEmpty() || section.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields!", "Reminder", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        String sql = "UPDATE register SET name=?, year=?, section=? WHERE student_id=?";
        
        try (Connection conn = DriverManager.getConnection(DB_URL);
             PreparedStatement pstmt = conn.prepareStatement(sql)) {
            
            pstmt.setString(1, name);
            pstmt.setString(2, year);
            pstmt.setString(3, section);
            pstmt.setString(4, studentId);
            
            pstmt.executeUpdate();
            
            JOptionPane.showMessageDialog(this, "Updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            
            // Balik sa Dashboard
            new DASHBOARD().setVisible(true);
            this.dispose();
            
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Update failed:\n" + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
