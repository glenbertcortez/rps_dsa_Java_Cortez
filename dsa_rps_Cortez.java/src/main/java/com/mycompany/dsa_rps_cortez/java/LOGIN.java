    private boolean validateLogin(String username, String password) {
        String sql = "SELECT * FROM Users WHERE username = ? AND password = ?";
        
        try (Connection conn = DriverManager.getConnection(DB_URL);
             PreparedStatement pstmt = conn.prepareStatement(sql)) {
            
            pstmt.setString(1, username);
            pstmt.setString(2, password);
            
            ResultSet rs = pstmt.executeQuery();
            return rs.next(); // true kung may nakitang tugma
            
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, "Database connection error", ex);
            JOptionPane.showMessageDialog(this, 
                "Database Error:\n" + ex.getMessage() + "\n\nPath: " + DB_URL, 
                "Connection Failed", 
                JOptionPane.ERROR_MESSAGE);
            return false;
        }
    }

    private void performLogin() {
        String username = jTextField1.getText().trim();
        String password = new String(jPasswordField1.getPassword());
        
        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Please fill in Username and Password!", 
                "Reminder", 
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        if (validateLogin(username, password)) {
            JOptionPane.showMessageDialog(this, 
                "Success! Welcome, " + username + "!", 
                "Login Success ✅", 
                JOptionPane.INFORMATION_MESSAGE);
            
            // Kapag tama ang login:
            new DASHBOARD().setVisible(true); // Pumunta agad sa Dashboard
            this.dispose(); // Isara ang Login form
        } else {
            JOptionPane.showMessageDialog(this, 
                "Wrong Username and Password!", 
                "Login Failed ❌",   
                JOptionPane.ERROR_MESSAGE);
            
            jTextField1.setText("");
            jPasswordField1.setText("");
        }
    }

